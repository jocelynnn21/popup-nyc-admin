-- Resource tables required by the expanded POPUP.NYC admin area.
-- Safe to run more than once in the Supabase SQL editor.

create table if not exists public.llm_providers (
  id bigint generated by default as identity primary key,
  name text not null unique,
  created_datetime_utc timestamptz not null default now(),
  modified_datetime_utc timestamptz not null default now()
);

create table if not exists public.llm_models (
  id bigint generated by default as identity primary key,
  name text not null,
  provider_model_id text not null,
  llm_provider_id bigint not null references public.llm_providers(id) on delete restrict,
  is_temperature_supported boolean not null default true,
  created_datetime_utc timestamptz not null default now(),
  modified_datetime_utc timestamptz not null default now()
);

create table if not exists public.images (
  id uuid primary key default gen_random_uuid(),
  url text,
  image_description text,
  additional_context text,
  celebrity_recognition text,
  is_common_use boolean not null default false,
  is_public boolean not null default false,
  profile_id uuid references public.profiles(id) on delete set null,
  created_datetime_utc timestamptz not null default now(),
  modified_datetime_utc timestamptz not null default now()
);

create table if not exists public.caption_requests (
  id bigint generated by default as identity primary key,
  image_id uuid not null references public.images(id) on delete restrict,
  profile_id uuid references public.profiles(id) on delete set null,
  created_datetime_utc timestamptz not null default now(),
  modified_datetime_utc timestamptz not null default now()
);

create table if not exists public.llm_prompt_chains (
  id bigint generated by default as identity primary key,
  caption_request_id bigint not null references public.caption_requests(id) on delete cascade,
  created_datetime_utc timestamptz not null default now(),
  modified_datetime_utc timestamptz not null default now()
);

create table if not exists public.humor_flavors (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  description text,
  is_pinned boolean not null default false,
  created_datetime_utc timestamptz not null default now(),
  modified_datetime_utc timestamptz not null default now()
);

create table if not exists public.humor_flavor_steps (
  id bigint generated by default as identity primary key,
  humor_flavor_id bigint not null references public.humor_flavors(id) on delete cascade,
  order_by integer not null,
  description text,
  llm_model_id bigint references public.llm_models(id) on delete restrict,
  llm_system_prompt text,
  llm_user_prompt text,
  llm_temperature numeric,
  is_hidden boolean not null default false,
  created_datetime_utc timestamptz not null default now(),
  modified_datetime_utc timestamptz not null default now()
);

create table if not exists public.humor_flavor_mix (
  id bigint generated by default as identity primary key,
  humor_flavor_id bigint not null unique references public.humor_flavors(id) on delete cascade,
  caption_count integer not null check (caption_count > 0),
  created_datetime_utc timestamptz not null default now(),
  modified_datetime_utc timestamptz not null default now()
);

create table if not exists public.terms (
  id bigint generated by default as identity primary key,
  term text not null,
  definition text not null,
  example text not null,
  priority integer not null default 0,
  term_type_id bigint,
  created_datetime_utc timestamptz not null default now(),
  modified_datetime_utc timestamptz not null default now()
);

create table if not exists public.caption_examples (
  id bigint generated by default as identity primary key,
  caption text not null,
  image_description text not null,
  explanation text not null,
  priority integer not null default 0,
  caption_example_category_id bigint,
  image_id uuid references public.images(id) on delete set null,
  created_datetime_utc timestamptz not null default now(),
  modified_datetime_utc timestamptz not null default now()
);

create table if not exists public.llm_model_responses (
  id uuid primary key default gen_random_uuid(),
  caption_request_id bigint not null references public.caption_requests(id) on delete cascade,
  llm_model_id bigint not null references public.llm_models(id) on delete restrict,
  llm_prompt_chain_id bigint references public.llm_prompt_chains(id) on delete set null,
  llm_model_response text,
  llm_system_prompt text,
  llm_user_prompt text,
  llm_temperature numeric,
  processing_time_seconds numeric not null default 0,
  profile_id uuid references public.profiles(id) on delete set null,
  created_datetime_utc timestamptz not null default now(),
  modified_datetime_utc timestamptz not null default now()
);

create table if not exists public.allowed_signup_domains (
  id bigint generated by default as identity primary key,
  apex_domain text not null unique,
  created_datetime_utc timestamptz not null default now(),
  modified_datetime_utc timestamptz not null default now()
);

create table if not exists public.whitelist_email_addresses (
  id bigint generated by default as identity primary key,
  email_address text not null unique,
  created_datetime_utc timestamptz not null default now(),
  modified_datetime_utc timestamptz not null default now()
);

do $$
declare resource_table text;
begin
  foreach resource_table in array array[
    'llm_providers', 'llm_models', 'images', 'caption_requests',
    'llm_prompt_chains', 'humor_flavors', 'humor_flavor_steps',
    'humor_flavor_mix', 'terms', 'caption_examples',
    'llm_model_responses', 'allowed_signup_domains',
    'whitelist_email_addresses'
  ] loop
    execute format('alter table public.%I enable row level security', resource_table);
    execute format('drop policy if exists "superadmin access" on public.%I', resource_table);
    execute format(
      'create policy "superadmin access" on public.%I for all to authenticated using (public.is_superadmin(auth.uid())) with check (public.is_superadmin(auth.uid()))',
      resource_table
    );
    execute format('grant select, insert, update, delete on public.%I to authenticated', resource_table);
  end loop;
end $$;

grant usage, select on sequence public.llm_providers_id_seq to authenticated;
grant usage, select on sequence public.llm_models_id_seq to authenticated;
grant usage, select on sequence public.caption_requests_id_seq to authenticated;
grant usage, select on sequence public.llm_prompt_chains_id_seq to authenticated;
grant usage, select on sequence public.humor_flavors_id_seq to authenticated;
grant usage, select on sequence public.humor_flavor_steps_id_seq to authenticated;
grant usage, select on sequence public.humor_flavor_mix_id_seq to authenticated;
grant usage, select on sequence public.terms_id_seq to authenticated;
grant usage, select on sequence public.caption_examples_id_seq to authenticated;
grant usage, select on sequence public.allowed_signup_domains_id_seq to authenticated;
grant usage, select on sequence public.whitelist_email_addresses_id_seq to authenticated;
